<?php

namespace App\Models;

use App\Enums\UserRole;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;

class User extends Authenticatable
{
    use HasFactory, Notifiable;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'name',
        'username',
        'email',
        'password',
        'is_active',
        'failed_login_attempts',
        'locked_at',
        'must_change_password',
        'two_factor_enabled',
        'two_factor_secret',
        'last_login_at',
        'last_login_ip',
        'email_verified_at',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var list<string>
     */
    protected $hidden = [
        'password',
        'remember_token',
        'two_factor_secret',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
            'is_active' => 'boolean',
            'failed_login_attempts' => 'integer',
            'locked_at' => 'datetime',
            'must_change_password' => 'boolean',
            'two_factor_enabled' => 'boolean',
            'two_factor_secret' => 'encrypted',
            'last_login_at' => 'datetime',
        ];
    }

    /**
     * Roles assigned to the user.
     */
    public function roles(): BelongsToMany
    {
        return $this->belongsToMany(Role::class, 'user_roles')
            ->withPivot('assigned_at')
            ->withTimestamps();
    }

    /**
     * Audit logs generated by this user.
     */
    public function auditLogs(): HasMany
    {
        return $this->hasMany(AuditLog::class);
    }

    /**
     * Check if user is locked.
     */
    public function isLocked(): bool
    {
        return $this->locked_at !== null;
    }

    /**
     * Check if user has a specific role by enum or string slug.
     */
    public function hasRole(UserRole|string $role): bool
    {
        $roleSlug = $role instanceof UserRole ? $role->value : $role;

        return $this->roles->contains('slug', $roleSlug);
    }

    /**
     * Check if user has any of the given roles.
     */
    public function hasAnyRole(array $roles): bool
    {
        foreach ($roles as $role) {
            if ($this->hasRole($role)) {
                return true;
            }
        }

        return false;
    }

    /**
     * Check if MFA should be enforced for this user based on their roles.
     */
    public function requiresMfa(): bool
    {
        if (! $this->two_factor_enabled) {
            return false;
        }

        return $this->hasRole(UserRole::PHARMACY_MANAGER) || $this->hasRole(UserRole::SYSTEM_ADMINISTRATOR);
    }

    /**
     * Check if user has access to clinical/patient/sales/dispensing business data.
     */
    public function canAccessBusinessData(): bool
    {
        if ($this->roles->isEmpty()) {
            return false;
        }

        return $this->roles->contains(function (Role $role) {
            $enumRole = UserRole::tryFrom($role->slug);
            return $enumRole ? $enumRole->hasBusinessDataAccess() : false;
        });
    }
}
